FROM RAG_DB.RAG_SCHEMA.EXTRACTED_DOCUMENTS
ORDER BY FILE_NAME;


-- Create the chunk table

CREATE TABLE IF NOT EXISTS RAG_DB.RAG_SCHEMA.DOCUMENT_CHUNKS (
    CHUNK_ID VARCHAR DEFAULT UUID_STRING(),
    DOCUMENT_ID VARCHAR,
    FILE_NAME VARCHAR,
    CHUNK_TEXT VARCHAR,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


-- Populate the table

INSERT INTO RAG_DB.RAG_SCHEMA.DOCUMENT_CHUNKS
    (DOCUMENT_ID, FILE_NAME, CHUNK_TEXT)
SELECT
    D.DOCUMENT_ID,
    D.FILE_NAME,
    F.VALUE::VARCHAR AS CHUNK_TEXT
FROM RAG_DB.RAG_SCHEMA.EXTRACTED_DOCUMENTS D,
LATERAL FLATTEN(
    INPUT => SNOWFLAKE.CORTEX.SPLIT_TEXT_RECURSIVE_CHARACTER(
        D.EXTRACTED_TEXT,
        CASE
            WHEN D.FILE_TYPE = 'md' THEN 'markdown'
            ELSE 'none'
        END,
        1500,
        200
    )
) F
WHERE D.EXTRACTED_TEXT IS NOT NULL
  AND LENGTH(TRIM(D.EXTRACTED_TEXT)) > 0;


-- Validate the chunks

SELECT
    FILE_NAME,
    COUNT(*) AS CHUNK_COUNT,
    MIN(LENGTH(CHUNK_TEXT)) AS MIN_CHUNK_LENGTH,
    MAX(LENGTH(CHUNK_TEXT)) AS MAX_CHUNK_LENGTH
FROM RAG_DB.RAG_SCHEMA.DOCUMENT_CHUNKS
GROUP BY FILE_NAME
ORDER BY FILE_NAME;

-- Inspect the content

SELECT
    FILE_NAME,
    CHUNK_ID,
    LEFT(CHUNK_TEXT, 250) AS CHUNK_PREVIEW
FROM RAG_DB.RAG_SCHEMA.DOCUMENT_CHUNKS
ORDER BY FILE_NAME
LIMIT 20;


-- Create the Cortex Search service

CREATE OR REPLACE CORTEX SEARCH SERVICE
    RAG_DB.RAG_SCHEMA.RAG_SEARCH_SERVICE
    ON CHUNK_TEXT
    ATTRIBUTES FILE_NAME, DOCUMENT_ID
    WAREHOUSE = RAG_WH
    TARGET_LAG = '1 hour'
    AS
    SELECT
        CHUNK_ID,
        CHUNK_TEXT,
        FILE_NAME,
        DOCUMENT_ID
    FROM RAG_DB.RAG_SCHEMA.DOCUMENT_CHUNKS;


