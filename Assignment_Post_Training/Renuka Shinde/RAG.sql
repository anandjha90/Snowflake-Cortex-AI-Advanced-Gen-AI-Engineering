INSERT INTO RAG_DB.RAG_SCHEMA.EXTRACTED_DOCUMENTS
    (FILE_NAME, FILE_TYPE, EXTRACTED_TEXT,
     WORD_COUNT, CHARACTER_COUNT)
WITH FILES AS (
    SELECT
        '01_snowflake_overview.txt' AS FILE_NAME,
        'txt' AS FILE_TYPE
    UNION ALL
    SELECT '02_rag_basics.txt', 'txt'
    UNION ALL
    SELECT '03_data_governance.txt', 'txt'
    UNION ALL
    SELECT '04_cortex_rag_test.pdf', 'pdf'
),
PARSED AS (
    SELECT
        FILE_NAME,
        FILE_TYPE,
        AI_PARSE_DOCUMENT(
            TO_FILE(
                '@RAG_DB.RAG_SCHEMA.RAG_DOCUMENT_STAGE',
                FILE_NAME
            ),
            {'mode': 'OCR'}
        ) AS PARSE_RESULT
    FROM FILES
),
EXTRACTED AS (
    SELECT
        FILE_NAME,
        FILE_TYPE,
        PARSE_RESULT:content::VARCHAR
            AS EXTRACTED_TEXT
    FROM PARSED
)
SELECT
    FILE_NAME,
    FILE_TYPE,
    EXTRACTED_TEXT,
    ARRAY_SIZE(SPLIT(EXTRACTED_TEXT, ' ')),
    LENGTH(EXTRACTED_TEXT)
FROM EXTRACTED
WHERE EXTRACTED_TEXT IS NOT NULL
  AND LENGTH(TRIM(EXTRACTED_TEXT)) > 0;


-- Verify extraction

SELECT
