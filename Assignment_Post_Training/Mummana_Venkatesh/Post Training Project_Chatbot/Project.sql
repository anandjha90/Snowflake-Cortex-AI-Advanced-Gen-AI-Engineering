CREATE TABLE IF NOT EXISTS RAG_PROJECT_DB.DOCUMENTS.LEAVE_POLICY_CHUNKS ( CHUNK_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1, FILE_NAME VARCHAR(500), CHUNK_TEXT VARCHAR(16777216) );



SELECT AI_PARSE_DOCUMENT(TO_FILE('@RAG_PROJECT_DB.DOCUMENTS.PDF_STAGE', 'Employee_Leave_Policy.pdf'), OBJECT_CONSTRUCT('mode','OCR')) AS EXTRACTED_DOCUMENT;

INSERT INTO RAG_PROJECT_DB.DOCUMENTS.LEAVE_POLICY_CHUNKS
    (FILE_NAME, CHUNK_TEXT)
WITH parsed AS (
    SELECT
        AI_PARSE_DOCUMENT(
            TO_FILE(
                '@RAG_PROJECT_DB.DOCUMENTS.PDF_STAGE',
                'Employee_Leave_Policy.pdf'
            ),
            OBJECT_CONSTRUCT('mode', 'OCR')
        ):content::VARCHAR AS DOCUMENT_TEXT
),
chunk_numbers AS (
    SELECT
        ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1 AS CHUNK_INDEX
    FROM TABLE(GENERATOR(ROWCOUNT => 1000))
)
SELECT
    'Employee_Leave_Policy.pdf',
    SUBSTR(
        parsed.DOCUMENT_TEXT,
        chunk_numbers.CHUNK_INDEX * 500 + 1,
        500
    )
FROM parsed
CROSS JOIN chunk_numbers
WHERE parsed.DOCUMENT_TEXT IS NOT NULL
  AND chunk_numbers.CHUNK_INDEX * 500
      < LENGTH(parsed.DOCUMENT_TEXT);

SELECT
    CHUNK_ID,
    FILE_NAME,
    LENGTH(CHUNK_TEXT) AS CHUNK_LENGTH,
    CHUNK_TEXT
FROM RAG_PROJECT_DB.DOCUMENTS.LEAVE_POLICY_CHUNKS
ORDER BY CHUNK_ID;


CREATE OR REPLACE CORTEX SEARCH SERVICE RAG_PROJECT_DB.DOCUMENTS.LEAVE_POLICY_SEARCH ON CHUNK_TEXT WAREHOUSE = COMPUTE_WH TARGET_LAG = '1 hour' AS SELECT CHUNK_ID::VARCHAR AS CHUNK_ID, FILE_NAME, CHUNK_TEXT FROM RAG_PROJECT_DB.DOCUMENTS.LEAVE_POLICY_CHUNKS;

