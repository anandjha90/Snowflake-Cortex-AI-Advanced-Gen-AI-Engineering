-- ============================================================================
-- Snowflake Cortex Search & AI Functions Setup Pipeline: HR Policies Use Case
-- Reference Architecture: RAG Application with Cortex Search
-- ============================================================================

-- 1. SETUP ENVIRONMENT, DATABASE, SCHEMA, WAREHOUSE & STAGE
CREATE DATABASE IF NOT EXISTS HR_POLICY_DB;
CREATE SCHEMA IF NOT EXISTS HR_POLICY_DB.PUBLIC;
USE DATABASE HR_POLICY_DB;
USE SCHEMA PUBLIC;

CREATE WAREHOUSE IF NOT EXISTS HR_RAG_WH
  WAREHOUSE_SIZE = 'X-SMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

USE WAREHOUSE HR_RAG_WH;

-- Create internal stage with directory enabled
CREATE OR REPLACE STAGE HR_DOCS_STAGE
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  DIRECTORY = (ENABLE = TRUE);


-- 2. EXTRACT RAW DOCUMENT CONTENT USING TO_FILE, BUILD_SCOPED_FILE_URL, AND AI_PARSE_DOCUMENT
CREATE OR REPLACE TEMPORARY TABLE RAW_HR_DOCUMENTS AS
WITH FILE_TABLE AS (
  SELECT 
    RELATIVE_PATH, 
    SIZE, 
    FILE_URL, 
    BUILD_SCOPED_FILE_URL(@HR_DOCS_STAGE, RELATIVE_PATH) AS SCOPED_FILE_URL, 
    TO_FILE('@HR_DOCS_STAGE', RELATIVE_PATH) AS DOC_FILE
  FROM DIRECTORY(@HR_DOCS_STAGE)
) 
SELECT 
  RELATIVE_PATH, 
  SIZE, 
  FILE_URL, 
  SCOPED_FILE_URL,
  SNOWFLAKE.CORTEX.AI_PARSE_DOCUMENT(
    DOC_FILE, 
    {'mode': 'LAYOUT'}
  ):content::STRING AS PARSED_TEXT,
  CURRENT_TIMESTAMP() AS PROCESSED_AT
FROM FILE_TABLE;


-- 3. STEP 1: CREATE THE DOCS_CHUNKS_TABLE EXPLICITLY
CREATE OR REPLACE TABLE DOCS_CHUNKS_TABLE (
  RELATIVE_PATH VARCHAR(16777216),
  SIZE NUMBER(38,0),
  FILE_URL VARCHAR(16777216),
  SCOPED_FILE_URL VARCHAR(16777216),
  CHUNK_INDEX INTEGER,
  CHUNK VARCHAR(16777216),
  CATEGORY VARCHAR(16777216),
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


-- 4. STEP 2: INSERT RECURSIVE CHUNKS INTO DOCS_CHUNKS_TABLE
INSERT INTO DOCS_CHUNKS_TABLE (
  RELATIVE_PATH, 
  SIZE, 
  FILE_URL, 
  SCOPED_FILE_URL, 
  CHUNK_INDEX, 
  CHUNK, 
  CATEGORY
)
WITH CHUNKED AS (
  SELECT
    RELATIVE_PATH,
    SIZE,
    FILE_URL,
    SCOPED_FILE_URL,
    SNOWFLAKE.CORTEX.SPLIT_TEXT_RECURSIVE_CHARACTER(
      PARSED_TEXT,
      'markdown',   -- Split target format
      1000,         -- Chunk size target
      200           -- Overlap size
    ) AS CHUNKS_ARRAY
  FROM RAW_HR_DOCUMENTS
)
SELECT
  RELATIVE_PATH,
  SIZE,
  FILE_URL,
  SCOPED_FILE_URL,
  C.INDEX::INTEGER AS CHUNK_INDEX,
  C.VALUE::STRING AS CHUNK,
  CAST(NULL AS STRING) AS CATEGORY -- Initialized as null for the update step
FROM CHUNKED,
LATERAL FLATTEN(INPUT => CHUNKS_ARRAY) C;


-- 5. STEP 3: UPDATE CATEGORY USING CLASSIFY_TEXT
-- Classify each chunk into standardized HR policy categories
UPDATE DOCS_CHUNKS_TABLE
SET CATEGORY = SNOWFLAKE.CORTEX.CLASSIFY_TEXT(
  CHUNK,
  ['Paid Time Off & Leave', 'Code of Conduct & Ethics', 'Compensation & Performance', 'Remote Work & Equipment', 'Benefits & Health']
):label::STRING;

-- Verify Chunking, Indexing, and Categorization Results
SELECT RELATIVE_PATH, CHUNK_INDEX, CATEGORY, SUBSTR(CHUNK, 1, 100) AS CHUNK_PREVIEW 
FROM DOCS_CHUNKS_TABLE 
WHERE CHUNK_INDEX = 0 
LIMIT 10;


-- 6. CREATE CORTEX SEARCH SERVICE
-- Create Cortex Search enabled on the chunked HR policy text
CREATE OR REPLACE CORTEX SEARCH SERVICE HR_POLICY_SEARCH_SERVICE
ON CHUNK
ATTRIBUTES CATEGORY, RELATIVE_PATH, CHUNK_INDEX
WAREHOUSE = HR_RAG_WH
TARGET_LAG = '1 hour'
AS (
  SELECT
    CHUNK,
    CATEGORY,
    RELATIVE_PATH,
    CHUNK_INDEX,
    SCOPED_FILE_URL
  FROM DOCS_CHUNKS_TABLE
);

--7. Test Cortex Search Service Output
SELECT SNOWFLAKE.CORTEX.SEARCH_PREVIEW(
'HR_POLICY_SEARCH_SERVICE',
'{
"query": "What is the parental leave policy?",
"columns": ["CHUNK", "CATEGORY", "FILE_NAME"],
"limit": 3
}'
);
